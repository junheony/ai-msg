#!/usr/bin/env node
// Write THIRD_PARTY_NOTICES.md: every package the shipped server can load at run time (the production dependency tree,
// read from node_modules — no network) and every package the UI sources import into the Vite bundle, with version and
// declared license. Build/test tooling that ships nothing is not listed.
//   node scripts/gen-third-party-notices.mjs            # writes THIRD_PARTY_NOTICES.md
//   node scripts/gen-third-party-notices.mjs --check    # exits 1 when the file is out of date
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const pkg = readJson(join(root, 'package.json'));

/** Node's lookup: the nearest node_modules/<name> walking up from the requiring package's directory. */
function locate(name, fromDir) {
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const p = join(dir, 'node_modules', name, 'package.json');
    if (existsSync(p)) return p;
    if (dir === root || dirname(dir) === dir) return null;
  }
}

const licenseOf = (m) =>
  typeof m.license === 'string' ? m.license
  : m.license?.type ?? (Array.isArray(m.licenses) ? m.licenses.map((l) => l.type ?? l).join(' OR ') : 'UNKNOWN');
const repoOf = (m) => {
  const r = typeof m.repository === 'string' ? m.repository : m.repository?.url;
  if (!r) return m.homepage ?? '';
  return r.replace(/^git\+/, '').replace(/\.git$/, '')
    .replace(/^(?:ssh:\/\/)?git@github\.com[:/]/, 'https://github.com/').replace(/^git:\/\//, 'https://')
    .replace(/^github:/, 'https://github.com/').replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1');
};

/** The whole dependency tree under `roots`, one row per name@version, sorted. */
function walk(roots) {
  const seen = new Map();
  const queue = roots.map((name) => [name, root]);
  while (queue.length) {
    const [name, from] = queue.shift();
    const p = locate(name, from);
    if (!p) { console.error(`missing from node_modules: ${name} (run npm ci)`); process.exit(1); }
    const m = readJson(p);
    const key = `${m.name}@${m.version}`;
    if (seen.has(key)) continue;
    seen.set(key, { name: m.name, version: m.version, license: licenseOf(m), repo: repoOf(m) });
    for (const dep of Object.keys({ ...m.dependencies, ...m.optionalDependencies })) {
      if (m.optionalDependencies?.[dep] && !locate(dep, dirname(p))) continue; // optional and not installed
      queue.push([dep, dirname(p)]);
    }
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

/** Bare module names imported by the UI sources (not tests): the roots of what Vite bundles into dist/ui. */
function uiRoots() {
  const names = new Set();
  const visit = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const f = join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'public') visit(f); continue; }
      if (!/\.(ts|tsx)$/.test(e.name) || /\.test\./.test(e.name)) continue;
      for (const [, spec] of readFileSync(f, 'utf8').matchAll(/(?:from|import)\s*\(?\s*'([^'.\/][^']*)'/g)) {
        names.add(spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0]);
      }
    }
  };
  visit(join(root, 'src', 'ui'));
  return [...names].filter((n) => !n.startsWith('node:')).sort();
}

const rows = walk(Object.keys(pkg.dependencies ?? {}));
const serverKeys = new Set(rows.map((r) => `${r.name}@${r.version}`));
const uiRows = walk(uiRoots()).filter((r) => !serverKeys.has(`${r.name}@${r.version}`));
const table = (list) => list.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`).join('\n');
const nonPermissive = [...rows, ...uiRows].filter((r) => !/^\(?(MIT|ISC|BSD-[23]-Clause|Apache-2\.0|0BSD)\)?$/.test(r.license));

const md = `# Third-party notices

AI-MSG is licensed under the Apache License 2.0 (see [LICENSE](LICENSE) and [NOTICE](NOTICE)). It depends on the
open-source packages below, each under its own license. The full license text of each package ships inside its
directory in \`node_modules\`.

Generated by \`node scripts/gen-third-party-notices.mjs\` from the installed production dependency tree. Do not edit by hand.

## Server run-time dependencies

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table(rows)}

## Bundled into the web UI

Packages the UI imports (and their dependencies) that Vite compiles into \`dist/ui\`, beyond those listed above.

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table(uiRows)}
${nonPermissive.length ? `
## Notes

${nonPermissive.map((r) => r.name === 'web-push'
  ? `- **web-push** (${r.version}) is licensed under the Mozilla Public License 2.0 (MPL-2.0), a file-level copyleft license. AI-MSG uses it unmodified as a separate package; its source is available at ${r.repo}. If you modify web-push's own files, those files must stay under MPL-2.0.`
  : `- **${r.name}** (${r.version}) is licensed under ${r.license}; see its LICENSE file.`).join('\n')}
` : ''}`;

const out = join(root, 'THIRD_PARTY_NOTICES.md');
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== md) { console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/gen-third-party-notices.mjs'); process.exit(1); }
  console.log(`THIRD_PARTY_NOTICES.md up to date (${rows.length + uiRows.length} packages)`);
} else {
  writeFileSync(out, md);
  console.log(`wrote THIRD_PARTY_NOTICES.md (${rows.length} server packages, ${uiRows.length} more bundled into the UI)`);
}
